// gh is signed out unless a test passes its own runner, so results never
// depend on the developer's real gh accounts.
const signedOutGh: GhRunner = async () => ({ exitCode: 1, stdout: "" });

function setup(
  cwd: string,
  options?: SetupOptions,
  prompts?: SetupPrompts,
  gh: GhRunner = signedOutGh,
): Promise<SetupResult> {
  return setupProject(cwd, options, prompts, { gh });
}

function signedInGh(
  logins: readonly string[],
  active: string,
  calls: (readonly string[])[] = [],
): GhRunner {
  return async (args) => {
    calls.push(args);
    if (args[0] === "auth" && args[1] === "status") {
      return {
        exitCode: 0,
        stdout: JSON.stringify({
          hosts: {
            "github.com": logins.map((login) => ({
              state: "success",
              active: login === active,
              login,
            })),
          },
        }),
      };
    }
    if (args[0] === "auth" && args[1] === "token") {
      const user = args[args.indexOf("--user") + 1];
      return logins.includes(user ?? "")
        ? { exitCode: 0, stdout: `token-for-${user}\n` }
        : { exitCode: 1, stdout: "" };
    }
    return { exitCode: 1, stdout: "" };
  };
}

// Setup writes agent credentials to the machine-wide file; keep it in a temp
// directory so tests never touch the real ~/.config.
const configHome = await mkdtemp(join(tmpdir(), "agent-cage-config-"));
process.env.XDG_CONFIG_HOME = configHome;
const globalEnvPath = join(configHome, "agent-cage", "env");
// Setup reads the Codex login and config.toml; keep the developer's out of it.
const codexHome = await mkdtemp(join(tmpdir(), "agent-cage-codex-home-"));
process.env.CODEX_HOME = codexHome;

async function tempRepo(): Promise<string> {
  const cwd = await mkdtemp(join(tmpdir(), "agent-cage-setup-"));
  await writeFile(
    join(cwd, "package.json"),
    JSON.stringify({ scripts: { test: "node --test", typecheck: "tsc --noEmit" } }),
    "utf8",
  );
  await writeFile(join(cwd, "package-lock.json"), "{}\n", "utf8");
  return cwd;
}

function acceptingPrompts(): SetupPrompts {
  return {
    async input(_message, defaultValue) {
      return defaultValue;
    },
    async secret() {
      return "";
    },
    async confirm(message, defaultValue) {
      if (message.startsWith("Enable GitHub Actions")) return true;
      if (message.startsWith("Configure GitHub")) return false;
      return defaultValue;
    },
    close() {},
  };
}

test("setup detects commands and enables both local Docker and Actions", async () => {
  const cwd = await tempRepo();
  try {
    const result = await setup(cwd, {}, acceptingPrompts());
    const config = parse(await readFile(join(cwd, ".agent-cage.yml"), "utf8")) as {
      setup: string[];
      verify: string[];
      execution: string;
      actions: { enabled: boolean; agent_cage_version: string };
    };
    const workflow = await readFile(
      join(cwd, ".github", "workflows", "agent-cage.yml"),
      "utf8",
    );
    const reviewPolicy = await readFile(
      join(cwd, ".agent-cage", "review-policy.md"),
      "utf8",
    );
    const envExample = await readFile(join(cwd, ".agent-cage.env.example"), "utf8");

    assert.deepEqual(config.setup, ["npm ci"]);
    assert.deepEqual(config.verify, ["npm test"]);
    assert.equal(config.execution, "docker");
    assert.equal(config.actions.enabled, true);
    assert.equal(config.actions.agent_cage_version, "0.1.0");
    assert.match(workflow, /Generated by Agent Cage/);
    assert.match(workflow, /AGENT_CAGE_EXECUTION: direct/);
    assert.match(reviewPolicy, /Agent Cage Review Policy/);
    assert.match(envExample, /GITHUB_TOKEN=/);
    assert.ok(result.created.includes(".agent-cage/review-policy.md"));
    assert.ok(result.created.includes(".agent-cage.env.example"));
    assert.equal(result.actionsEnabled, true);
  } finally {
    await rm(cwd, { recursive: true, force: true });
  }
});

