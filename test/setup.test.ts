test("setup writes local secrets with restricted permissions", async () => {
  const cwd = await tempRepo();
  const prompts: SetupPrompts = {
    async input(_message, defaultValue) {
      return defaultValue;
    },
    async secret(message) {
      return message === "GITHUB_TOKEN" ? "github-secret" : "openai-secret";
    },
    async confirm(message, defaultValue) {
      if (message.startsWith("Configure local")) return true;
      if (message.startsWith("Enable GitHub Actions")) return false;
      return defaultValue;
    },
    close() {},
  };
  try {
    await setupProject(cwd, {}, prompts);
    const envPath = join(cwd, ".codex-cage.env");
    const content = await readFile(envPath, "utf8");
    const mode = (await stat(envPath)).mode & 0o777;

    assert.match(content, /GITHUB_TOKEN=github-secret/);
    assert.equal(mode, 0o600);
  } finally {
    await rm(cwd, { recursive: true, force: true });
  }
});

test("setup never overwrites existing review policy or env example", async () => {
  const cwd = await tempRepo();
  try {
    await mkdir(join(cwd, ".codex-cage"), { recursive: true });
    await writeFile(
      join(cwd, ".codex-cage", "review-policy.md"),
      "custom policy\n",
      "utf8",
    );
    const completeExample = [
      "# Copy this file to .codex-cage.env and fill in local secrets.",
      "OPENAI_API_KEY=",
      "GITHUB_TOKEN=",
      "# Required only for Linear issue URLs.",
      "LINEAR_API_KEY=",
      "CUSTOM_KEY=",
      "",
    ].join("\n");
    await writeFile(join(cwd, ".codex-cage.env.example"), completeExample, "utf8");

    const result = await setupProject(cwd, { yes: true, actions: false });

    assert.equal(
      await readFile(join(cwd, ".codex-cage", "review-policy.md"), "utf8"),
      "custom policy\n",
    );
    assert.equal(
      await readFile(join(cwd, ".codex-cage.env.example"), "utf8"),
      completeExample,
    );
    assert.ok(!result.created.includes(".codex-cage/review-policy.md"));
    assert.ok(!result.created.includes(".codex-cage.env.example"));
  } finally {
    await rm(cwd, { recursive: true, force: true });
  }
});

