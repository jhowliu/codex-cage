import assert from "node:assert/strict";
import { mkdir, mkdtemp, readFile, rm, stat, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { parse } from "yaml";
import { setupProject, type SetupPrompts } from "../src/setup.js";

async function tempRepo(): Promise<string> {
  const cwd = await mkdtemp(join(tmpdir(), "codex-cage-setup-"));
  await writeFile(
    join(cwd, "package.json"),
    JSON.stringify({ scripts: { test: "node --test", typecheck: "tsc --noEmit" } }),
    "utf8",
  );
  await writeFile(join(cwd, "package-lock.json"), "{}\n", "utf8");
  return cwd;
}

function acceptingPrompts(): SetupPrompts {
  return {
    async input(_message, defaultValue) {
      return defaultValue;
    },
    async secret() {
      return "";
    },
    async confirm(message, defaultValue) {
      if (message.startsWith("Enable GitHub Actions")) return true;
      if (message.startsWith("Configure GitHub")) return false;
      return defaultValue;
    },
    close() {},
  };
}

test("setup detects commands and enables both local Docker and Actions", async () => {
  const cwd = await tempRepo();
  try {
    const result = await setupProject(cwd, {}, acceptingPrompts());
    const config = parse(await readFile(join(cwd, ".codex-cage.yml"), "utf8")) as {
      setup: string[];
      verify: string[];
      execution: string;
      actions: { enabled: boolean; codex_cage_version: string };
    };
    const workflow = await readFile(
      join(cwd, ".github", "workflows", "codex-cage.yml"),
      "utf8",
    );
    const reviewPolicy = await readFile(
      join(cwd, ".codex-cage", "review-policy.md"),
      "utf8",
    );
    const envExample = await readFile(join(cwd, ".codex-cage.env.example"), "utf8");

    assert.deepEqual(config.setup, ["npm ci"]);
    assert.deepEqual(config.verify, ["npm test"]);
    assert.equal(config.execution, "docker");
    assert.equal(config.actions.enabled, true);
    assert.equal(config.actions.codex_cage_version, "0.1.0");
    assert.match(workflow, /Generated by Codex Cage/);
    assert.match(workflow, /CODEX_CAGE_EXECUTION: direct/);
    assert.match(reviewPolicy, /Codex Cage Review Policy/);
    assert.match(envExample, /GITHUB_TOKEN=/);
    assert.ok(result.created.includes(".codex-cage/review-policy.md"));
    assert.ok(result.created.includes(".codex-cage.env.example"));
    assert.equal(result.actionsEnabled, true);
  } finally {
    await rm(cwd, { recursive: true, force: true });
  }
});

test("setup is rerunnable and preserves unknown config", async () => {
  const cwd = await tempRepo();
  try {
    await writeFile(
      join(cwd, ".codex-cage.yml"),
      "# keep\nsetup:\n  - npm ci\nverify:\n  - npm test\nfuture_option: true\n",
      "utf8",
    );
    await setupProject(cwd, { yes: true, actions: false });
    const source = await readFile(join(cwd, ".codex-cage.yml"), "utf8");

    assert.match(source, /# keep/);
    assert.match(source, /future_option: true/);
    assert.match(source, /enabled: false/);
  } finally {
    await rm(cwd, { recursive: true, force: true });
  }
});

test("disabling Actions removes only a managed workflow", async () => {
  const cwd = await tempRepo();
  try {
    await setupProject(cwd, { yes: true, actions: true });
    const result = await setupProject(cwd, { yes: true, actions: false });

    assert.deepEqual(result.removed, [".github/workflows/codex-cage.yml"]);
    await assert.rejects(
      () => readFile(join(cwd, ".github", "workflows", "codex-cage.yml"), "utf8"),
      /ENOENT/,
    );
  } finally {
    await rm(cwd, { recursive: true, force: true });
  }
});

test("setup refuses to replace an unmanaged workflow", async () => {
  const cwd = await tempRepo();
  try {
    await mkdir(join(cwd, ".github", "workflows"), { recursive: true });
    await writeFile(
      join(cwd, ".github", "workflows", "codex-cage.yml"),
      "name: custom\n",
      "utf8",
    );

    await assert.rejects(
      () => setupProject(cwd, { yes: true, actions: true }),
      /not managed by Codex Cage/,
    );
  } finally {
    await rm(cwd, { recursive: true, force: true });
  }
});

