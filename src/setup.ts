export async function setupProject(
  cwd: string,
  options: SetupOptions = {},
  prompts?: SetupPrompts,
): Promise<SetupResult> {
  const configState = await loadCodexCageConfigFile(cwd);
  if (configState.status === "invalid") {
    throw new Error(
      `.codex-cage.yml is invalid: ${configState.errors.map((error) => error.message).join("; ")}`,
    );
  }

  const ownsPrompts = prompts === undefined && options.yes !== true;
  const prompt = prompts ?? (options.yes === true ? null : createTerminalSetupPrompts());

  try {
    const detected = await detectProjectDefaults(cwd);
    const existing = configState.status === "valid" ? configState.config : null;
    const setup = await chooseCommands(
      "setup",
      existing?.setup ?? detected.setup,
      prompt,
    );
    const verify = await chooseCommands(
      "verification",
      existing?.verify ?? detected.verify,
      prompt,
    );
    if (verify.length === 0) {
      throw new Error("At least one verification command is required.");
    }

    const actionsEnabled =
      options.actions ??
      (prompt === null
        ? (existing?.actions.enabled ?? false)
        : await prompt.confirm(
            "Enable GitHub Actions issue automation?",
            existing?.actions.enabled ?? false,
          ));
    const actions = buildActionsConfig(existing, actionsEnabled);
    const updates = {
      setup,
      verify,
      git: existing?.git ?? {
        base: detected.baseBranch,
        author_name: "Codex Cage",
        author_email: "codex-cage@users.noreply.github.com",
      },
      execution: "docker",
      actions,
    } satisfies CodexCageConfigUpdates;

    if (prompt !== null && !(await prompt.confirm("Apply this configuration?", true))) {
      return {
        created: [],
        updated: [],
        removed: [],
        actionsEnabled,
        dryRun: options.dryRun ?? false,
        notices: [],
      };
    }

    const setupResult = await applySetup(
      cwd,
      configState,
      updates,
      options.dryRun ?? false,
    );
    if (!setupResult.dryRun) {
      setupResult.notices.push(
        ...(await configureLocalCredentials(cwd, prompt, setupResult)),
      );
    }
    const configureGithub =
      actionsEnabled &&
      (options.github ??
        (prompt === null
          ? false
          : await prompt.confirm(
              "Configure GitHub labels and Actions secrets now?",
              true,
            )));
    if (configureGithub && !setupResult.dryRun) {
      setupResult.notices.push(
        ...(await configureGithubRepository(cwd, actions, prompt)),
      );
    }
    return setupResult;
  } finally {
    if (ownsPrompts) prompt?.close();
  }
}

async function configureLocalCredentials(
  cwd: string,
  prompts: SetupPrompts | null,
  setupResult: SetupResult,
): Promise<string[]> {
  const notices: string[] = [];
  let changed = false;
  const envPath = join(cwd, ".codex-cage.env");
  const envExists = await fileExists(envPath);
  const env = await readCodexCageEnv(cwd);
  const needsOpenAi =
    env.OPENAI_API_KEY === undefined &&
    !(await fileExists(join(homedir(), ".codex", "auth.json")));
  const missing = [
    ...(needsOpenAi ? (["OPENAI_API_KEY"] as const) : []),
    ...(env.GITHUB_TOKEN === undefined && env.GH_TOKEN === undefined
      ? (["GITHUB_TOKEN"] as const)
      : []),
  ];

  for (const name of missing) {
    if (
      prompts === null ||
      !(await prompts.confirm(`Configure local ${name} now?`, false))
    ) {
      notices.push(`Local ${name} is not configured; add it to .codex-cage.env.`);
      continue;
    }
    const value = await prompts.secret(name);
    if (value === "") {
      notices.push(`Skipped empty local ${name}.`);
      continue;
    }
    await mergeEnvSecret(envPath, name, value);
    changed = true;
  }

  if (await fileExists(envPath)) {
    await chmod(envPath, 0o600);
    if (!envExists) setupResult.created.push(".codex-cage.env");
    else if (changed) setupResult.updated.push(".codex-cage.env");
  }
  return notices;
}

async function mergeEnvSecret(path: string, name: string, value: string): Promise<void> {
  if (value.includes("\n") || value.includes("\r")) {
    throw new Error(`${name} must not contain newlines.`);
  }
  const current = (await readOptionalFile(path)) ?? "";
  const assignment = `${name}=${quoteEnvValue(value)}`;
  const lines = current.split(/\r?\n/);
  const index = lines.findIndex(
    (line) => line.match(/^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)=/)?.[1] === name,
  );
  if (index === -1) {
    const separator = current === "" || current.endsWith("\n") ? "" : "\n";
    await atomicWriteSecret(path, `${current}${separator}${assignment}\n`);
    return;
  }
  lines[index] = assignment;
  await atomicWriteSecret(path, lines.join("\n"));
}

function quoteEnvValue(value: string): string {
  if (value.includes('"'))
    throw new Error("Credential values must not contain double quotes.");
  return /^[A-Za-z0-9_./:@+=-]+$/.test(value) ? value : `"${value}"`;
}

async function atomicWriteSecret(path: string, content: string): Promise<void> {
  await mkdir(dirname(path), { recursive: true });
  const tempPath = `${path}.${process.pid}.tmp`;
  try {
    await writeFile(tempPath, content, { encoding: "utf8", mode: 0o600 });
    await rename(tempPath, path);
    await chmod(path, 0o600);
  } finally {
    await rm(tempPath, { force: true });
  }
}

export function createTerminalSetupPrompts(): SetupPrompts {
  let muted = false;
  const terminalOutput = new Writable({
    write(chunk: string | Buffer, _encoding, callback) {
      if (!muted) output.write(chunk);
      callback();
    },
  });
  const terminal = createInterface({ input, output: terminalOutput, terminal: true });
  return {
    async input(message, defaultValue) {
      const answer = (await terminal.question(`${message} [${defaultValue}]: `)).trim();
      return answer === "" ? defaultValue : answer;
    },
    async secret(message) {
      output.write(`${message}: `);
      muted = true;
      try {
        return (await terminal.question("")).trim();
      } finally {
        muted = false;
        output.write("\n");
      }
    },
    async confirm(message, defaultValue) {
      const hint = defaultValue ? "Y/n" : "y/N";
      const answer = (await terminal.question(`${message} (${hint}): `))
        .trim()
        .toLowerCase();
      if (answer === "") return defaultValue;
      return answer === "y" || answer === "yes";
    },
    close() {
      terminal.close();
    },
  };
}

async function chooseCommands(
  kind: "setup" | "verification",
  defaults: string[],
  prompts: SetupPrompts | null,
): Promise<string[]> {
  if (prompts === null) return defaults;
  if (defaults.length > 0) {
    const summary = defaults.map((command) => `\n  - ${command}`).join("");
    if (await prompts.confirm(`Keep detected ${kind} commands?${summary}`, true)) {
      return defaults;
    }
  }

  const commands: string[] = [];
  do {
    const command = (await prompts.input(`Enter ${kind} command`, "")).trim();
    if (command !== "") commands.push(command);
  } while (await prompts.confirm(`Add another ${kind} command?`, false));
  return commands;
}

function buildActionsConfig(
  existing: CodexCageConfig | null,
  enabled: boolean,
): CodexCageConfig["actions"] {
  const current = existing?.actions;
  return {
    enabled,
    workflow: current?.workflow ?? ".github/workflows/codex-cage.yml",
    codex_cage_version: enabled
      ? (current?.codex_cage_version ?? readPackageVersion())
      : (current?.codex_cage_version ?? null),
    runner: current?.runner ?? "ubuntu-latest",
    timeout_minutes: current?.timeout_minutes ?? 90,
    container: current?.container ?? null,
    services: current?.services ?? {},
    labels: current?.labels ?? {
      run: "codex-cage:run",
      in_progress: "codex-cage:in-progress",
      ready: "codex-cage:ready-for-review",
      blocked: "codex-cage:blocked",
    },
  };
}

async function applySetup(
  cwd: string,
  configState: Awaited<ReturnType<typeof loadCodexCageConfigFile>> & {
    status: "missing" | "valid";
  },
  updates: CodexCageConfigUpdates,
  dryRun: boolean,
): Promise<SetupResult> {
  const actions = updates.actions;
  if (actions === undefined) throw new Error("Setup plan is missing Actions settings.");

  const workflowPath = resolveManagedPath(cwd, actions.workflow);
  const workflowExists = await fileExists(workflowPath);
  const result: SetupResult = {
    created: configState.status === "missing" ? [".codex-cage.yml"] : [],
    updated: configState.status === "valid" ? [".codex-cage.yml"] : [],
    removed: [],
    actionsEnabled: actions.enabled,
    dryRun,
    notices: [],
  };

  if (actions.enabled) {
    if (workflowExists) {
      await assertManagedWorkflow(workflowPath);
      result.updated.push(relative(cwd, workflowPath));
    } else {
      result.created.push(relative(cwd, workflowPath));
    }
  } else if (workflowExists && (await isManagedWorkflow(workflowPath))) {
    result.removed.push(relative(cwd, workflowPath));
  }

  const scaffoldChanges = await planScaffoldFiles(cwd);
  result.created.push(...scaffoldChanges.created);
  result.updated.push(...scaffoldChanges.updated);

  if (dryRun) return result;

  await updateCodexCageConfigFile(configState, updates);
  await ensureGitignore(cwd);
  await writeScaffoldFiles(cwd, scaffoldChanges);
  if (actions.enabled) {
    const version = actions.codex_cage_version;
    if (version === null)
      throw new Error("Actions requires a pinned Codex Cage version.");
    const workflow = generateGitHubActionsWorkflow({
      codexCageVersion: version,
      runsOn: actions.runner,
      timeoutMinutes: actions.timeout_minutes,
      labels: {
        run: actions.labels.run,
        inProgress: actions.labels.in_progress,
        ready: actions.labels.ready,
        blocked: actions.labels.blocked,
      },
      ...(actions.container === null
        ? {}
        : { container: toActionsRuntime(actions.container) }),
      services: Object.fromEntries(
        Object.entries(actions.services).map(([name, service]) => [
          name,
          toActionsRuntime(service),
        ]),
      ),
    });
    await atomicWrite(workflowPath, `${GENERATED_WORKFLOW_MARKER}${workflow}`);
  } else if (workflowExists && (await isManagedWorkflow(workflowPath))) {
    await rm(workflowPath);
  }

  return result;
}

async function configureGithubRepository(
  cwd: string,
  actions: CodexCageConfig["actions"],
  prompts: SetupPrompts | null,
): Promise<string[]> {
  const notices: string[] = [];
  const auth = await execa("gh", ["auth", "status"], { cwd, reject: false });
  if (auth.exitCode !== 0) {
    return ["GitHub CLI is not authenticated; run `gh auth login`, then rerun setup."];
  }

  const labels = [
    [actions.labels.run, "1d76db", "Trigger a Codex Cage run"],
    [actions.labels.in_progress, "fbca04", "Codex Cage is working on this issue"],
    [actions.labels.ready, "0e8a16", "Codex Cage opened a pull request"],
    [actions.labels.blocked, "d93f0b", "Codex Cage requires attention"],
  ] as const;
  for (const [name, color, description] of labels) {
    const label = await execa(
      "gh",
      [
        "label",
        "create",
        name,
        "--color",
        color,
        "--description",
        description,
        "--force",
      ],
      { cwd, reject: false },
    );
    if (label.exitCode !== 0) notices.push(`Could not create GitHub label ${name}.`);
  }

  const secretList = await execa("gh", ["secret", "list", "--json", "name"], {
    cwd,
    reject: false,
  });
  const configured =
    secretList.exitCode === 0 ? parseGithubNames(secretList.stdout) : new Set();
  for (const name of ["OPENAI_API_KEY", "CODEX_CAGE_GITHUB_TOKEN"] as const) {
    if (configured.has(name)) continue;
    if (prompts === null || !(await prompts.confirm(`Configure ${name} now?`, false))) {
      notices.push(
        `Missing Actions secret ${name}; configure it with \`gh secret set ${name}\`.`,
      );
      continue;
    }
    const value = await prompts.secret(name);
    if (value === "") {
      notices.push(`Skipped empty Actions secret ${name}.`);
      continue;
    }
    const secret = await execa("gh", ["secret", "set", name], {
      cwd,
      input: value,
      reject: false,
    });
    if (secret.exitCode !== 0)
      notices.push(`Could not configure Actions secret ${name}.`);
  }

  return notices;
}

function parseGithubNames(value: string): Set<string> {
  try {
    const parsed: unknown = JSON.parse(value);
    if (!Array.isArray(parsed)) return new Set();
    return new Set(
      parsed.flatMap((item) => {
        if (item === null || typeof item !== "object" || !("name" in item)) return [];
        return typeof item.name === "string" ? [item.name] : [];
      }),
    );
  } catch {
    return new Set();
  }
}

function toActionsRuntime(
  runtime: CodexCageConfig["actions"]["services"][string],
): GitHubActionsRuntime {
  return {
    image: runtime.image,
    ...(runtime.env === undefined ? {} : { env: runtime.env }),
    ...(runtime.ports === undefined ? {} : { ports: runtime.ports }),
    ...(runtime.options === undefined ? {} : { options: runtime.options }),
  };
}

async function detectProjectDefaults(cwd: string): Promise<ProjectDefaults> {
  const packageJson = await readPackageJson(cwd);
  const packageManager = await detectPackageManager(cwd);
  const setup = packageManager === null ? [] : [packageManager.setup];
  const scripts = packageJson?.scripts ?? {};
  const verify = selectVerifyCommands(packageManager?.run ?? "npm run", scripts);
  const baseBranch = await detectBaseBranch(cwd);
  return { setup, verify, baseBranch };
}

async function detectPackageManager(
  cwd: string,
): Promise<{ setup: string; run: string } | null> {
  if (await fileExists(join(cwd, "pnpm-lock.yaml")))
    return { setup: "pnpm install --frozen-lockfile", run: "pnpm" };
  if (await fileExists(join(cwd, "yarn.lock")))
    return { setup: "yarn install --immutable", run: "yarn" };
  if (await fileExists(join(cwd, "package-lock.json")))
    return { setup: "npm ci", run: "npm run" };
  return null;
}

function selectVerifyCommands(
  runPrefix: string,
  scripts: Record<string, string>,
): string[] {
  if (scripts.test !== undefined) {
    return [runPrefix === "npm run" ? "npm test" : `${runPrefix} test`];
  }
  if (scripts.typecheck !== undefined) return [`${runPrefix} typecheck`];
  if (scripts.build !== undefined) return [`${runPrefix} build`];
  return [];
}

async function readPackageJson(
  cwd: string,
): Promise<{ scripts?: Record<string, string> } | null> {
  try {
    const parsed: unknown = JSON.parse(await readFile(join(cwd, "package.json"), "utf8"));
    if (parsed === null || typeof parsed !== "object" || Array.isArray(parsed))
      return null;
    const scripts = "scripts" in parsed ? parsed.scripts : undefined;
    if (scripts === undefined) return {};
    if (scripts === null || typeof scripts !== "object" || Array.isArray(scripts))
      return {};
    return {
      scripts: Object.fromEntries(
        Object.entries(scripts).filter(
          (entry): entry is [string, string] => typeof entry[1] === "string",
        ),
      ),
    };
  } catch (error) {
    if (isNodeError(error) && error.code === "ENOENT") return null;
    throw error;
  }
}

async function detectBaseBranch(cwd: string): Promise<string> {
  const commands = [
    ["symbolic-ref", "--short", "refs/remotes/origin/HEAD"],
    ["branch", "--show-current"],
  ] as const;
  for (const args of commands) {
    const result = await execa("git", args, { cwd, reject: false });
    if (result.exitCode === 0 && result.stdout.trim() !== "") {
      return result.stdout.trim().replace(/^origin\//, "");
    }
  }
  return "main";
}

async function ensureGitignore(cwd: string): Promise<void> {
  const path = join(cwd, ".gitignore");
  const current = await readOptionalFile(path);
  const existing = new Set(
    (current ?? "")
      .split(/\r?\n/)
      .map((line) => line.trim())
      .filter(Boolean),
  );
  const missing = gitignoreEntries.filter((entry) => !existing.has(entry));
  if (missing.length === 0) return;
  const separator =
    current === undefined || current === "" || current.endsWith("\n") ? "" : "\n";
  await atomicWrite(path, `${current ?? ""}${separator}${missing.join("\n")}\n`);
}

type ScaffoldChanges = {
  created: string[];
  updated: string[];
};

async function planScaffoldFiles(cwd: string): Promise<ScaffoldChanges> {
  const created: string[] = [];
  const updated: string[] = [];

  const reviewPolicyFilePath = join(cwd, reviewPolicyPath);
  if (!(await fileExists(reviewPolicyFilePath))) {
    created.push(relative(cwd, reviewPolicyFilePath));
  }

  const envExampleFilePath = join(cwd, envExamplePath);
  if (!(await fileExists(envExampleFilePath))) {
    created.push(relative(cwd, envExampleFilePath));
  } else if (await missingEnvExampleKeys(envExampleFilePath)) {
    updated.push(relative(cwd, envExampleFilePath));
  }

  return { created, updated };
}

async function writeScaffoldFiles(cwd: string, changes: ScaffoldChanges): Promise<void> {
  const reviewPolicyFilePath = join(cwd, reviewPolicyPath);
  if (changes.created.includes(reviewPolicyPath)) {
    await atomicWrite(reviewPolicyFilePath, reviewPolicy);
  }

  const envExampleFilePath = join(cwd, envExamplePath);
  if (changes.created.includes(envExamplePath)) {
    await atomicWrite(envExampleFilePath, envExample);
  } else if (changes.updated.includes(envExamplePath)) {
    await mergeEnvExample(envExampleFilePath);
  }
}

async function missingEnvExampleKeys(path: string): Promise<boolean> {
  const current = await readOptionalFile(path);
  if (current === undefined) return true;
  const currentKeys = new Set(
    current
      .split(/\r?\n/)
      .map((line) => line.match(/^([A-Z0-9_]+)=/)?.[1])
      .filter((key): key is string => key !== undefined),
  );
  return envExample
    .split("\n")
    .map((line) => line.match(/^([A-Z0-9_]+)=/)?.[1])
    .some((key) => key !== undefined && !currentKeys.has(key));
}

async function mergeEnvExample(path: string): Promise<void> {
  const current = await readFile(path, "utf8");
  const currentKeys = new Set(
    current
      .split(/\r?\n/)
      .map((line) => line.match(/^([A-Z0-9_]+)=/)?.[1])
      .filter((key): key is string => key !== undefined),
  );
  const missingLines = envExample
    .split("\n")
    .filter((line) => line.trim() !== "")
    .filter((line) => {
      const key = line.match(/^([A-Z0-9_]+)=/)?.[1];
      return key === undefined || !currentKeys.has(key);
    })
    .filter((line) => !current.includes(line));

  if (missingLines.length === 0) return;
  const separator = current.endsWith("\n") ? "" : "\n";
  await atomicWrite(path, `${current}${separator}${missingLines.join("\n")}\n`);
}

function resolveManagedPath(cwd: string, relativePath: string): string {
  const path = resolve(cwd, relativePath);
  const relativePathFromCwd = relative(cwd, path);
  if (relativePathFromCwd.startsWith("..") || relativePathFromCwd === "") {
    throw new Error(`Managed path must stay inside the repository: ${relativePath}`);
  }
  return path;
}

async function assertManagedWorkflow(path: string): Promise<void> {
  if (!(await isManagedWorkflow(path))) {
    throw new Error(`${path} already exists and is not managed by Codex Cage.`);
  }
}

async function isManagedWorkflow(path: string): Promise<boolean> {
  return (await readFile(path, "utf8")).startsWith(GENERATED_WORKFLOW_MARKER);
}

async function atomicWrite(path: string, content: string): Promise<void> {
  await mkdir(dirname(path), { recursive: true });
  const tempPath = `${path}.${process.pid}.tmp`;
  try {
    await writeFile(tempPath, content, "utf8");
    await rename(tempPath, path);
  } finally {
    await rm(tempPath, { force: true });
  }
}

async function readOptionalFile(path: string): Promise<string | undefined> {
  try {
    return await readFile(path, "utf8");
  } catch (error) {
    if (isNodeError(error) && error.code === "ENOENT") return undefined;
    throw error;
  }
}

async function fileExists(path: string): Promise<boolean> {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

function isNodeError(error: unknown): error is NodeJS.ErrnoException {
  return error instanceof Error && "code" in error;
}
