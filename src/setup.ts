async function detectProjectDefaults(cwd: string): Promise<ProjectDefaults> {
  const { setup, verify, toolchains } = await detectProject(projectFilesAt(cwd));
  const baseBranch = await detectBaseBranch(cwd);
  return { setup, verify, toolchains, baseBranch };
}

async function detectBaseBranch(cwd: string): Promise<string> {
  const commands = [
    ["symbolic-ref", "--short", "refs/remotes/origin/HEAD"],
    ["branch", "--show-current"],
  ] as const;
  for (const args of commands) {
    const result = await execa("git", args, { cwd, reject: false });
    if (result.exitCode === 0 && result.stdout.trim() !== "") {
      return result.stdout.trim().replace(/^origin\//, "");
    }
  }
  return "main";
}

async function ensureGitignore(cwd: string): Promise<void> {
  const path = join(cwd, ".gitignore");
  const current = await readOptionalFile(path);
  const existing = new Set(
    (current ?? "")
      .split(/\r?\n/)
      .map((line) => line.trim())
      .filter(Boolean),
  );
  const missing = gitignoreEntries.filter((entry) => !existing.has(entry));
  if (missing.length === 0) return;
  const separator =
    current === undefined || current === "" || current.endsWith("\n") ? "" : "\n";
  await atomicWrite(path, `${current ?? ""}${separator}${missing.join("\n")}\n`);
}

type ScaffoldChanges = {
  created: string[];
  updated: string[];
};

async function planScaffoldFiles(
  cwd: string,
  runtimeDockerfile: string | null,
): Promise<ScaffoldChanges> {
  const created: string[] = [];
  const updated: string[] = [];

  // An existing Dockerfile at this path is kept and only referenced.
  if (
    runtimeDockerfile !== null &&
    !(await fileExists(join(cwd, runtimeDockerfilePath)))
  ) {
    created.push(runtimeDockerfilePath);
  }

  const reviewPolicyFilePath = join(cwd, reviewPolicyPath);
  if (!(await fileExists(reviewPolicyFilePath))) {
    created.push(relative(cwd, reviewPolicyFilePath));
  }

  const envExampleFilePath = join(cwd, envExamplePath);
  if (!(await fileExists(envExampleFilePath))) {
    created.push(relative(cwd, envExampleFilePath));
  } else if (await missingEnvExampleKeys(envExampleFilePath)) {
    updated.push(relative(cwd, envExampleFilePath));
  }

  return { created, updated };
}

async function writeScaffoldFiles(
  cwd: string,
  changes: ScaffoldChanges,
  runtimeDockerfile: string | null,
): Promise<void> {
  if (runtimeDockerfile !== null && changes.created.includes(runtimeDockerfilePath)) {
    await atomicWrite(join(cwd, runtimeDockerfilePath), runtimeDockerfile);
  }

  const reviewPolicyFilePath = join(cwd, reviewPolicyPath);
  if (changes.created.includes(reviewPolicyPath)) {
    await atomicWrite(reviewPolicyFilePath, reviewPolicy);
  }

  const envExampleFilePath = join(cwd, envExamplePath);
  if (changes.created.includes(envExamplePath)) {
    await atomicWrite(envExampleFilePath, envExample);
  } else if (changes.updated.includes(envExamplePath)) {
    await mergeEnvExample(envExampleFilePath);
  }
}

async function missingEnvExampleKeys(path: string): Promise<boolean> {
  const current = await readOptionalFile(path);
  if (current === undefined) return true;
  const currentKeys = new Set(
    current
      .split(/\r?\n/)
      .map((line) => line.match(/^([A-Z0-9_]+)=/)?.[1])
      .filter((key): key is string => key !== undefined),
  );
  return envExample
    .split("\n")
    .map((line) => line.match(/^([A-Z0-9_]+)=/)?.[1])
    .some((key) => key !== undefined && !currentKeys.has(key));
}

async function mergeEnvExample(path: string): Promise<void> {
  const current = await readFile(path, "utf8");
  const currentKeys = new Set(
    current
      .split(/\r?\n/)
      .map((line) => line.match(/^([A-Z0-9_]+)=/)?.[1])
      .filter((key): key is string => key !== undefined),
  );
  const missingLines = envExample
    .split("\n")
    .filter((line) => line.trim() !== "")
    .filter((line) => {
      const key = line.match(/^([A-Z0-9_]+)=/)?.[1];
      return key === undefined || !currentKeys.has(key);
    })
    .filter((line) => !current.includes(line));

  if (missingLines.length === 0) return;
  const separator = current.endsWith("\n") ? "" : "\n";
  await atomicWrite(path, `${current}${separator}${missingLines.join("\n")}\n`);
}

function resolveManagedPath(cwd: string, relativePath: string): string {
  const path = resolve(cwd, relativePath);
  const relativePathFromCwd = relative(cwd, path);
  if (relativePathFromCwd.startsWith("..") || relativePathFromCwd === "") {
    throw new Error(`Managed path must stay inside the repository: ${relativePath}`);
  }
  return path;
}

async function assertManagedWorkflow(path: string): Promise<void> {
  if (!(await isManagedWorkflow(path))) {
    throw new Error(`${path} already exists and is not managed by Codex Cage.`);
  }
}

async function isManagedWorkflow(path: string): Promise<boolean> {
  return (await readFile(path, "utf8")).startsWith(GENERATED_WORKFLOW_MARKER);
}

async function atomicWrite(path: string, content: string): Promise<void> {
  await mkdir(dirname(path), { recursive: true });
  const tempPath = `${path}.${process.pid}.tmp`;
  try {
    await writeFile(tempPath, content, "utf8");
    await rename(tempPath, path);
  } finally {
    await rm(tempPath, { force: true });
  }
}

async function readOptionalFile(path: string): Promise<string | undefined> {
  try {
    return await readFile(path, "utf8");
  } catch (error) {
    if (isNodeError(error) && error.code === "ENOENT") return undefined;
    throw error;
  }
}

async function fileExists(path: string): Promise<boolean> {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

function isNodeError(error: unknown): error is NodeJS.ErrnoException {
  return error instanceof Error && "code" in error;
}
